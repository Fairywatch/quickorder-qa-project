_PAIRS = sorted(MOTS.items(), key=lambda kv: -len(kv[0]))
_RE = re.compile(r"\b(" + u"|".join(re.escape(k) for k, _ in _PAIRS) + r")\b")
_LOOKUP = dict(_PAIRS)


def _applique(texte):
    for avant, apres in PHRASES:
        texte = texte.replace(avant, apres)
    return _RE.sub(lambda mo: _LOOKUP[mo.group(1)], texte)


def accentuer(texte, html=False):
    """Restaure les accents. Si html=True, epargne les blocs <pre> et <code>."""
    if not texte:
        return texte
    if not html:
        return _applique(texte)
    morceaux = re.split(r"(<pre\b.*?</pre>|<code\b.*?</code>)", texte, flags=re.S)
    for i, m in enumerate(morceaux):
        if i % 2 == 0:
            morceaux[i] = _applique(m)
    return u"".join(morceaux)
